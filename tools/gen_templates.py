"""Builds crates/club685-core/src/templates.rs from the fixture frames.

Geometry (96 dpi, rekordbox 6.8.5): the "NN.NBars" text is right aligned, its last ink column E sits 2 px left of the
playhead. Digit cells are 8 px apart, the "." takes 4 px. Text rows are row top + 1 .. row top + 11.
"""
import glob, os, sys
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
FIX = os.path.join(HERE, '..', 'fixtures')
OUT = os.path.join(HERE, '..', 'crates', 'club685-core', 'src', 'templates.rs')

# strings read from the fixtures (deck1, deck2); 3band-paused/-playing-a/-playing-b, blue/rgb/session captures
TRUTH = {
    '3band-paused': ('45.1', '113.1'), '3band-playing-a': ('85.3', '69.1'), '3band-playing-b': ('86.1', '69.3'),
    'blue-paused': ('45.1', '113.1'), 'rgb-paused': ('45.1', '113.1'),
    'session-000': ('45.1', '113.1'), 'session-020': ('45.1', '113.1'), 'session-036': ('48.2', '115.2'),
    'session-040': ('53.3', '120.3'), 'session-045': ('59.3', '127.2'), 'session-050': ('66.1', '133.4'),
    'session-055': ('72.3', '140.2'),
}
ROW_TOPS = (151, 220)
CURSOR = 1280
E = CURSOR - 2
CELL_W, CELL_H = 9, 11
SUFFIX_W = 30
OFFS = [-37, -49, -57, -65]  # tenths, units, tens, hundreds (cell origin relative to E)


def alpha(a):
    r, g, b = a[..., 0], a[..., 1], a[..., 2]
    ok = (r <= 24) & (b >= 0x30) & (g * 100 >= b * 45) & (g * 100 <= b * 66)
    return np.where(ok, b, 0)


digit_inst = {str(d): [] for d in range(10)}
suffix_inst = []
for name, strs in TRUTH.items():
    a = np.array(Image.open(os.path.join(FIX, name + '.png')).convert('RGB')).astype(int)
    for top, s in zip(ROW_TOPS, strs):
        al = alpha(a[top + 1:top + 1 + CELL_H, :2560])
        digits = list(reversed(s.replace('.', '')))
        for d, o in zip(digits, OFFS):
            x0 = E + o
            digit_inst[d].append(al[:, x0 - 1:x0 - 1 + CELL_W])
        suffix_inst.append(al[:, E - SUFFIX_W + 1:E + 1])

def med(lst):
    return np.median(np.stack(lst), axis=0).astype(int)

lines = ['// Generated by tools/gen_templates.py from the fixture frames. Do not edit.', '',
         f'pub const CELL_W: usize = {CELL_W};', f'pub const CELL_H: usize = {CELL_H};',
         f'pub const SUFFIX_W: usize = {SUFFIX_W};', '']
lines.append(f'pub const DIGITS: [[u8; {CELL_W * CELL_H}]; 10] = [')
for d in range(10):
    t = med(digit_inst[str(d)])
    lines.append('    [' + ', '.join(str(v) for v in t.flatten()) + '],')
lines.append('];')
t = med(suffix_inst)
lines.append(f'pub const SUFFIX: [u8; {SUFFIX_W * CELL_H}] = [' + ', '.join(str(v) for v in t.flatten()) + '];')
with open(OUT, 'w') as f:
    f.write('\n'.join(lines) + '\n')
print('wrote', OUT)
